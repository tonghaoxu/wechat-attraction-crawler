    # 开放/关闭
    "开放时间", "开园", "闭园", "开馆", "闭馆", "开院", "闭院",
    "暂停", "恢复", "关闭", "延长开放", "夜场", "开放",
    # 公告类
    "公告", "通告", "通知", "提示", "须知", "预警",
    # 票务/价格
    "门票", "票价", "价格", "调价", "免票", "免费", "优惠",
    "预约", "购票", "售票", "放票", "限流", "限量", "停售", "实名",
    # 交通/设施
    "索道", "缆车", "游船", "摆渡", "停运", "检修", "交通", "停车",
