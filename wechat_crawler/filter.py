"""文章相关性过滤：只保留对游客出行有实际影响的公告类内容。

判定规则（基于标题 + 摘要，在抓取正文之前执行，节省请求）：
  1. 命中任一排除词 -> 丢弃（招聘、党建、文创带货等，即使同时含购票等词也丢弃）
  2. 命中任一保留词 -> 保留（开闭园、票价、临时闭馆、交通、天气预警等）
  3. 都未命中 -> 丢弃（白名单模式：默认认为与游客出行无关）

关键词可在 config.yaml 的 crawl.filter 中覆盖；未配置时使用下方默认值。
"""

# 保留：影响游客出行的公告类内容
